#!/usr/bin/env node
// The code-size gate.
//
// docs/CODE_SIZE.md (planning repo) adopted the target on 2026-10-22: no new production source
// file above 500 non-blank lines, and a file that was already over the line is split when it is
// next materially changed. The document calls itself "a review target, not a CI gate yet", and
// planning #747 is the reason it cannot stay that way: four production files crossed the line
// after adoption, the table never heard about them, and three recorded counts drifted. A rule
// whose only memory is a table somebody must remember to edit decays silently.
//
// This script is the memory. It measures the production tree the document defines
// (backend/src, admin/src, mobile/src, mobile/app, website, scripts), and compares it with
// scripts/code-size-exceptions.json - the recorded rows. It fails when:
//
//   * a file is over the target and has no row          -> it was added, or it grew past 500
//   * a row's recorded count differs from the tree      -> the file changed and the row did not
//   * a row's file is at or below the target            -> the row is stale, delete it
//   * a row's file does not exist                       -> the row points at nothing
//
// Every failure names the file and the number, so the fix is an edit, not an investigation.
// Exit 0 = every file agrees with the table, 1 = one does not, 2 = the gate itself could not run.
//
// One more list: "declarations". The document excludes `*.d.ts` because type declarations carry no
// behaviour; `admin/src/lib/api-types.ts` is that same file under a name the pattern does not
// match (0 runtime declarations, 40 interfaces and type aliases). Rather than teach the gate to
// guess by parsing, the exceptions file names the file, and the gate checks that it still exists.
//
// Usage:
//   node scripts/code-size-gate.mjs [--target <n>] [--repo <dir>] [--exceptions <file>]
//
//   --target       the line (default: the exceptions file's "target", else 500)
//   --repo         the tree to measure (default: this repository) - the test hook
//   --exceptions   the recorded rows (default: <repo>/scripts/code-size-exceptions.json)

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_TARGET = 500;
const EXIT_BLOCKED = 1;
const EXIT_ERROR = 2;

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// The document's list: "application code under backend/src, admin/src, mobile/src, mobile/app,
// website/ and scripts/". A root that is absent is not an error - a checkout without `website`
// still has code to measure.
const SOURCE_ROOTS = ["backend/src", "admin/src", "mobile/src", "mobile/app", "website", "scripts"];
const SOURCE_EXTENSIONS = new Set([".cs", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"]);

// Build output, dependencies and test trees are not production source. `__tests__` is the one
// directory the document names; the rest are artifacts a local run leaves behind.
const SKIP_DIRECTORIES = new Set([
  "node_modules",
  "bin",
  "obj",
  ".next",
  ".expo",
  "out",
  "dist",
  "build",
  "coverage",
  "__tests__",
  "fixtures",
]);

// Tests, EF-generated code and declarations are excluded by the document. The snapshot file is
// generated too, and its name does not end in `Designer`.
const EXCLUDED_FILE = [
  /\.test\.[^/\\]+$/,
  /\.d\.ts$/,
  /\.Designer\.cs$/,
  /(^|[/\\])ApplicationDbContextModelSnapshot\.cs$/,
];

// The migration bodies are generated by `dotnet ef migrations add` and are append-only - a
// 1 400-line migration is the shape of the change it records, and it must never be split. The
// document excludes generated code; its parenthetical names the Designer and the snapshot
// because those were the ones it was looking at.
const EXCLUDED_DIRECTORIES = ["backend/src/FuelFlow.API/Migrations"];

function parseArgs(argv) {
  const options = { target: null, repo: repoRoot, exceptions: null };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--target") {
      index += 1;
      options.target = Number(argv[index]);
    } else if (arg === "--repo") {
      index += 1;
      options.repo = resolve(argv[index]);
    } else if (arg === "--exceptions") {
      index += 1;
      options.exceptions = resolve(argv[index]);
    } else if (arg.startsWith("-")) {
      throw new Error(`unknown option: ${arg}`);
    } else {
      throw new Error(`unexpected argument: ${arg} - this gate takes no positional arguments`);
    }
  }

  if (options.target !== null && (!Number.isInteger(options.target) || options.target <= 0)) {
    throw new Error(`--target must be a positive whole number, got ${options.target}`);
  }

  options.exceptions ??= join(options.repo, "scripts", "code-size-exceptions.json");
  return options;
}

// The document's own measure: non-blank lines. Blank lines say nothing about how much a file
// carries, and counting them would let a reformat move the number without changing the code.
function countNonBlankLines(text) {
  return text.split(/\r?\n/).filter((line) => line.trim() !== "").length;
}

function toPosix(path) {
  return path.split(sep).join("/");
}

function collectSourceFiles(root, repo) {
  const files = [];

  const walk = (directory) => {
    let entries;
    try {
      entries = readdirSync(directory, { withFileTypes: true });
    } catch {
      // A root the checkout does not have, or a directory that vanished mid-walk.
      return;
    }

    for (const entry of entries) {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) {
        if (SKIP_DIRECTORIES.has(entry.name)) continue;
        if (EXCLUDED_DIRECTORIES.includes(toPosix(relative(repo, full)))) continue;
        walk(full);
        continue;
      }
      if (!entry.isFile()) continue;

      const extension = entry.name.slice(entry.name.lastIndexOf("."));
      if (!SOURCE_EXTENSIONS.has(extension)) continue;
      if (EXCLUDED_FILE.some((pattern) => pattern.test(toPosix(full)))) continue;

      files.push(full);
    }
  };

  walk(root);
  return files;
}

function measure(repo, declarations) {
  const measured = new Map();

  for (const root of SOURCE_ROOTS) {
    for (const file of collectSourceFiles(join(repo, root), repo)) {
      const path = toPosix(relative(repo, file));
      if (declarations.has(path)) continue;
      measured.set(path, countNonBlankLines(readFileSync(file, "utf8")));
    }
  }

  return measured;
}

function loadExceptions(path) {
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(path, "utf8"));
  } catch (error) {
    throw new Error(`the exceptions file ${path} could not be read: ${error.message}`);
  }
  if (!parsed || !Array.isArray(parsed.exceptions)) {
    throw new Error(`the exceptions file ${path} has no "exceptions" array`);
  }

  const declarations = new Set();
  if (parsed.declarations !== undefined) {
    if (!Array.isArray(parsed.declarations)) {
      throw new Error(`the exceptions file ${path} has a "declarations" that is not a list`);
    }
    for (const entry of parsed.declarations) {
      if (typeof entry !== "string" || entry.trim() === "") {
        throw new Error(`the exceptions file ${path} has a declarations entry that is not a path`);
      }
      if (declarations.has(toPosix(entry))) {
        throw new Error(`the exceptions file ${path} lists ${entry} twice in "declarations"`);
      }
      declarations.add(toPosix(entry));
    }
  }

  const rows = new Map();
  for (const row of parsed.exceptions) {
    if (!row || typeof row.path !== "string" || !Number.isInteger(row.lines)) {
      throw new Error(`the exceptions file ${path} has a row without a "path" and an integer "lines"`);
    }
    if (typeof row.reason !== "string" || row.reason.trim() === "") {
      throw new Error(
        `the exceptions file ${path} has no reason for ${row.path} - a row without a reason is a rumour`,
      );
    }
    if (rows.has(toPosix(row.path))) {
      throw new Error(`the exceptions file ${path} lists ${row.path} twice`);
    }
    rows.set(toPosix(row.path), row);
  }

  return { target: parsed.target ?? DEFAULT_TARGET, declarations, rows };
}

function evaluate(measured, rows, target) {
  const over = [];
  const drifted = [];
  const stale = [];
  const missing = [];

  for (const [path, lines] of measured) {
    if (lines <= target) continue;
    over.push({ path, lines });

    const row = rows.get(path);
    if (!row) continue;
    if (row.lines !== lines) drifted.push({ path, lines, recorded: row.lines });
  }

  for (const [path, row] of rows) {
    if (!measured.has(path)) {
      missing.push({ path, recorded: row.lines });
      continue;
    }
    if (measured.get(path) <= target) stale.push({ path, lines: measured.get(path) });
  }

  const unrecorded = over.filter((entry) => !rows.has(entry.path));
  unrecorded.sort((a, b) => b.lines - a.lines);
  drifted.sort((a, b) => a.path.localeCompare(b.path));
  stale.sort((a, b) => a.path.localeCompare(b.path));
  missing.sort((a, b) => a.path.localeCompare(b.path));

  return { unrecorded, drifted, stale, missing };
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const { target: recordedTarget, declarations, rows } = loadExceptions(options.exceptions);
  const target = options.target ?? recordedTarget;

  // A declarations entry for a file that is not there is the same rot as a stale row, and it
  // would silently stop covering a file that came back under the same name.
  const vanishedDeclarations = [...declarations].filter((path) => !existsSync(join(options.repo, path)));

  const measured = measure(options.repo, declarations);
  const result = evaluate(measured, rows, target);

  const over = [...measured.entries()].filter(([, lines]) => lines > target).length;
  console.log(`== code size (target ${target} non-blank lines, ${measured.size} production files)`);
  console.log(
    `   ${over} file(s) over the line, ${rows.size} recorded in ${relative(options.repo, options.exceptions) || options.exceptions}`,
  );

  const problems = [];

  for (const path of vanishedDeclarations) {
    problems.push(
      `   ---  ${path}\n` +
        `            is listed under "declarations", but the file does not exist. Delete the entry.`,
    );
  }

  for (const { path, lines } of result.unrecorded) {
    problems.push(
      `   ${lines}  ${path}\n` +
        `            is over the target and has no row in the exceptions file. Split it by\n` +
        `            responsibility, or add a row with its reason and a follow-up issue.`,
    );
  }

  for (const { path, lines, recorded } of result.drifted) {
    problems.push(
      `   ${lines}  ${path}\n` +
        `            the exceptions file records ${recorded}. The file changed and the row did not:\n` +
        `            split it, or set the row to ${lines} in the same pull request.`,
    );
  }

  for (const { path, lines } of result.stale) {
    problems.push(
      `   ${lines}  ${path}\n` +
        `            is at or below the target and still has a row. Delete the row.`,
    );
  }

  for (const { path, recorded } of result.missing) {
    problems.push(
      `   ---  ${path}\n` +
        `            the exceptions file records ${recorded} lines, but the file does not exist.\n` +
        `            Delete the row, or fix its path.`,
    );
  }

  if (problems.length === 0) {
    console.log("\nEvery production file agrees with the exceptions table.");
    return 0;
  }

  console.error(`\n${problems.length} file(s) disagree with the exceptions table:\n`);
  console.error(problems.join("\n\n"));
  console.error(
    `\nThe table is ${relative(options.repo, options.exceptions) || options.exceptions}; the rule and the\n` +
      `measurement are docs/CODE_SIZE.md in the planning repo.`,
  );
  return EXIT_BLOCKED;
}

try {
  process.exit(main());
} catch (error) {
  console.error(`\nThe code-size gate could not run: ${error.message}`);
  process.exit(EXIT_ERROR);
}
